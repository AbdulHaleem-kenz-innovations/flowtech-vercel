// Only this component changes — everything else in the file stays the same

export default function FormWrapper() {
  const { language } = useLanguage();
  const t = langData[language.toLowerCase()].contact_section;

  // ── STATE ──────────────────────────────────────────────────────
  // formData: tracks what the user is typing in each field
  const [formData, setFormData] = useState({
    name: "",
    email: "",
    countryCode: "+966", // default matches your UI (SA +966)
    phoneNumber: "",
    message: "",
  });

  const countryCodes = [
    { label: "IN +91", value: "+91" },
    { label: "US +1", value: "+1" },
    { label: "UK +44", value: "+44" },
    { label: "SA +966", value: "+966" },
    { label: "AE +971", value: "+971" },
  ];

  // termsAccepted: tracks whether the checkbox is checked
  const [termsAccepted, setTermsAccepted] = useState(false);

  // loading: true while axios request is in flight
  // prevents double submissions and shows spinner on button
  const [loading, setLoading] = useState(false);

  // status: 'idle' | 'success' | 'error'
  // controls which feedback UI to show
  const [status, setStatus] = useState("idle");

  // feedbackMsg: the actual message text to show the user
  const [feedbackMsg, setFeedbackMsg] = useState("");

  // ── HANDLERS ───────────────────────────────────────────────────

  // handleChange: one function handles ALL input fields
  // e.target.name tells us which field changed (name, email, or message)
  // e.target.value is what the user typed
  const handleChange = (e) => {
    const { name, value } = e.target;
    setFormData((prev) => ({
      ...prev, // keep all other fields as they are
      [name]: value, // only update the field that changed
    }));
  };

  // handleSubmit: runs when the form is submitted
  const handleSubmit = async (e) => {
    e.preventDefault(); // prevent browser page reload

    // Combine country code + number into one string for the backend
    // Result: "+91 9876543210"
    const fullPhone = `${formData.countryCode} ${formData.phoneNumber.trim()}`;

    // Frontend phone validation
    if (!formData.phoneNumber.trim()) {
      setStatus("error");
      setFeedbackMsg("Please enter your phone number.");
      return;
    }

    if (!/^\d{5,15}$/.test(formData.phoneNumber.trim())) {
      setStatus("error");
      setFeedbackMsg("Please enter a valid phone number (digits only).");
      return;
    }
    // ── Frontend validation ──
    // Quick checks before even hitting the backend
    // Saves unnecessary API calls for obvious errors

    if (
      !formData.name.trim() ||
      !formData.email.trim() ||
      !formData.message.trim()
    ) {
      setStatus("error");
      setFeedbackMsg("Please fill in all fields before submitting.");
      return;
    }

    if (!termsAccepted) {
      setStatus("error");
      setFeedbackMsg("Please accept the terms and conditions to proceed.");
      return;
    }

    // ── API call ──
    setLoading(true); // disable button, show loading text
    setStatus("idle"); // reset any previous feedback
    setFeedbackMsg("");

    try {
      const response = await axios.post(
        `${import.meta.env.VITE_API_URL}/api/contact`,
        // `${import.meta.env.VITE_API_URL}/`,
        {
          name: formData.name.trim(),
          email: formData.email.trim(),
          phone: fullPhone,
          message: formData.message.trim(),
        },
      );

      // ── Success (201) ──
      // Backend saved to DB and sent email successfully
      setStatus("success");
      setFeedbackMsg(response.data.message);

      // Reset the form after successful submission
      setFormData({
        name: "",
        email: "",
        countryCode: "+966",
        phoneNumber: "",
        message: "",
      });
      setTermsAccepted(false);
    } catch (error) {
      // axios throws for any non-2xx status (400, 429, 500, etc.)
      // error.response exists when the server replied with an error
      // error.response is undefined when there's a network error (backend down)

      if (error.response) {
        // Server responded with an error status
        // Use the message our backend sent — it's already user-friendly
        setStatus("error");
        setFeedbackMsg(error.response.data.message);
      } else {
        // Network error — backend is unreachable
        setStatus("error");
        setFeedbackMsg(
          "Unable to reach the server. Please check your connection and try again.",
        );
      }
    } finally {
      // finally runs whether request succeeded or failed
      // Always re-enable the button after the request completes
      setLoading(false);
    }
  };

  // ── JSX ────────────────────────────────────────────────────────
  return (
    <div
      className="bg-white content-stretch flex flex-col gap-8 md:gap-[27px] items-start justify-center max-w-[500px] overflow-clip pb-10 md:pb-[45px] pt-10 md:pt-[30px] px-6 md:px-[30px] relative rounded-[7px] shrink-0 w-full md:w-[500px] lg:w-[420px] xl:w-[500px]"
      data-name="Form Wrapper"
    >
      <div className="flex flex-col gap-4 items-start w-full">
        <div className="bg-[#2df9a7]/15 px-3 py-1.5 rounded-full flex gap-2 items-center">
          <div className="size-[12px] flex items-center justify-center">
            <ImageWithFallback
              src={imgImage}
              alt=""
              className="size-full object-contain"
            />
          </div>
          <span className="font-['Geist'] font-semibold text-[10px] text-[#0f9101] uppercase tracking-wide">
            {t.form_badge}
          </span>
        </div>
        <div className="flex flex-wrap gap-x-2 items-center">
          <span
            className="bg-clip-text font-['Geist'] font-medium text-[20px] md:text-[23px] text-black/40"
            style={{
              backgroundImage:
                "linear-gradient(-88.8998deg, rgba(0, 0, 0, 0.4) 5%, rgb(0, 0, 0) 50%)",
            }}
          >
            {t.form_title_p1}
          </span>
          <span className="font-['Playfair_Display'] italic text-[20px] md:text-[23px] text-black/60">
            {t.form_title_italic}
          </span>
        </div>
      </div>

      {/* ── Feedback Banner ── */}
      {/* Shows success or error message after submission */}
      {status === "success" && (
        <div className="w-full bg-green-50 border border-green-200 rounded-[7px] px-4 py-3">
          <p className="font-['Geist'] text-[13px] text-green-700 leading-snug">
            ✅ {feedbackMsg}
          </p>
        </div>
      )}

      {status === "error" && (
        <div className="w-full bg-red-50 border border-red-200 rounded-[7px] px-4 py-3">
          <p className="font-['Geist'] text-[13px] text-red-600 leading-snug">
            ⚠️ {feedbackMsg}
          </p>
        </div>
      )}

      <form
        className="content-stretch flex flex-col gap-4 items-center justify-center relative shrink-0 w-full"
        onSubmit={handleSubmit}
      >
        {/* Name Field */}
        <div className="w-full flex flex-col gap-1.5">
          <label className="font-['Geist'] text-[10px] text-black/60 uppercase">
            {t.label_name}
          </label>
          <input
            className="w-full bg-[#f5f5f5] rounded-[7px] p-4 outline-none font-['Geist'] text-[16px] text-black placeholder:text-black/30"
            placeholder={t.placeholder_name}
            name="name"
            value={formData.name}
            onChange={handleChange}
            disabled={loading}
          />
        </div>

        {/* Email Field */}
        <div className="w-full flex flex-col gap-1.5">
          <label className="font-['Geist'] text-[10px] text-black/60 uppercase">
            {t.label_email}
          </label>
          <input
            className="w-full bg-[#f5f5f5] rounded-[7px] p-4 outline-none font-['Geist'] text-[16px] text-black placeholder:text-black/30"
            placeholder={t.placeholder_email}
            type="email"
            name="email"
            value={formData.email}
            onChange={handleChange}
            disabled={loading}
          />
        </div>

        {/* Phone Number Field */}
        <div className="w-full flex flex-col gap-1.5">
          <label className="font-['Geist'] text-[10px] text-black/60 uppercase">
            Phone Number
          </label>
          <div className="flex gap-2 w-full">
            {/* Country Code Dropdown */}
            <select
              name="countryCode"
              value={formData.countryCode}
              onChange={handleChange}
              disabled={loading}
              className="bg-[#f5f5f5] rounded-[7px] px-3 py-4 outline-none font-['Geist'] text-[14px] text-black shrink-0 cursor-pointer"
            >
              {countryCodes.map((c) => (
                <option key={c.value} value={c.value}>
                  {c.label}
                </option>
              ))}
            </select>

            {/* Phone Number Input */}
            <input
              className="w-full bg-[#f5f5f5] rounded-[7px] p-4 outline-none font-['Geist'] text-[16px] text-black placeholder:text-black/30"
              placeholder="5 XXXXXXX"
              type="tel"
              name="phoneNumber"
              value={formData.phoneNumber}
              onChange={handleChange}
              disabled={loading}
            />
          </div>
        </div>

        {/* Message Field */}
        <div className="w-full flex flex-col gap-1.5">
          <label className="font-['Geist'] text-[10px] text-black/60 uppercase">
            {t.label_message}
          </label>
          <textarea
            className="w-full bg-[#f5f5f5] rounded-[7px] p-4 h-[100px] outline-none font-['Geist'] text-[16px] text-black placeholder:text-black/30 resize-none"
            placeholder={t.placeholder_message}
            name="message"
            value={formData.message}
            onChange={handleChange}
            disabled={loading}
          />
        </div>

        {/* Terms Checkbox */}
        <div className="flex gap-3 items-start w-full py-2">
          <input
            type="checkbox"
            className="mt-1"
            id="terms"
            checked={termsAccepted}
            onChange={(e) => setTermsAccepted(e.target.checked)}
            disabled={loading}
          />
          <label
            htmlFor="terms"
            className="font-['Geist'] text-[13px] text-black/60 leading-tight"
          >
            {t.terms_p1}{" "}
            <span className="text-[#110fdf] font-semibold cursor-pointer">
              {t.terms_link}
            </span>
          </label>
        </div>

        {/* Submit Button */}
        <button
          type="submit"
          disabled={loading}
          className={`relative overflow-hidden flex items-center justify-center
            w-fit mx-auto sm:mx-0
            px-5 py-2.5 sm:px-6 sm:py-3 md:px-8 md:py-4
            text-[13px] sm:text-[14px] md:text-[16px]
            rounded-full
            bg-[linear-gradient(78deg,#001CA9_0%,#046CE4_100%)]
            border border-white/20
            text-white uppercase whitespace-nowrap
            font-['Geist']
            transition-all duration-300
            glare-btn
            ${
              loading
                ? "opacity-60 cursor-not-allowed scale-100"
                : "cursor-pointer hover:scale-105 active:scale-95"
            }`}
        >
          {loading ? "Sending..." : t.send_button}
        </button>
      </form>
    </div>
  );
}

